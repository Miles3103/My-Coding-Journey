int	ft_sqrt(int nb)
{
	long	i;
	long	n;

	if (nb < 0)
		return (0);
	n = (long)nb;
	i = 0;
	while (i * i <= n)
	{
		if (i * i == n)
			return ((int)i);
		i++;
	}
	return (0);
}
