#include <unistd.h>
#include <stdio.h>
void	ft_swap(int *a, int *b)
{
	int tmp;
	tmp = *a;
	*a = *b;
	*b = tmp;
}

int main(void)
{
	int x;
	int y;
	x = 23;
	y = 42;
	printf("%d, %d\n",x,y);
	ft_swap(&x,&y);
	printf("%d , %d\n", x, y);
}

